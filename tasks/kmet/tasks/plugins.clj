(ns kmet.tasks.plugins
  "The generated plugin catalog — the `bb generate-plugins` task.

   `kmet.app.catalog` renders a composition row's card (its `:name :inject
   :provide`) without loading the plugin's namespace; this task produces the
   committed file it reads: `modules/app/src/kmet/app/plugin-catalog.edn`,
   generated from the `srce/defplugin` declarations in the module sources.

   A declaration is a top-level form `(srce/defplugin sym {:name … :apply …})`
   — `defplugin` refuses anything but a map literal at compile time, so the
   scanner reads the literal and never evaluates it. Reader conditionals are
   read with the `#{:clj}` feature view on every host: the catalog is a
   committed, host-independent file, so a branch a host alone would select is
   not catalogued — such a plugin still composes, and its card is then read
   from the loaded var instead. `kmet.tasks.test-plugins` holds the committed
   file to a fresh render."
  (:require [babashka.fs :as fs]
            [clojure.string :as str]
            [edamame.core :as e]
            [kmet.srce :as srce]
            [kmet.tasks.modules :as modules]))

(def catalog-path
  "The committed catalog this task writes."
  "modules/app/src/kmet/app/plugin-catalog.edn")

(def header
  ";; The generated plugin catalog — do not hand-edit.
;;
;; Generated by `bb generate-plugins` from the srce/defplugin declarations in
;; the module sources (kmet.tasks.plugins), and held to a fresh scan by
;; kmet.tasks.test-plugins. It is composition documentation and validation, not
;; a registry: `kmet --app new --dump-config` reads a built-in row's card from
;; here instead of loading the plugin's namespace, and a row whose source is
;; missing from here still composes by reading the var.
")

(def ^:private read-opts
  "Read declarations without evaluating them. `#{:clj}` is the portable view
   (the `:default` branches): the same file renders on bb, Jolt and the JVM,
   and a host-only branch is simply not catalogued. The reader macros are
   spelled out because edamame refuses each one by default — `'` is `:quote`
   (`:syntax-quote` is the backtick), `#'` is `:var`."
  {:read-cond :allow
   :features #{:clj}
   :quote true
   :syntax-quote true
   :auto-resolve (fn [alias] (or alias 'kmet.app))
   :deref true
   :fn true
   :var true
   :regex true})

(defn- defplugin-form?
  [form]
  (and (seq? form)
       (symbol? (first form))
       (= "defplugin" (name (first form)))))

(defn- bad-declaration [form message]
  (throw (ex-info message {:type :kmet.plugins/bad-declaration :form form})))

(defn- declaration [ns-sym form]
  (let [[_ sym plugin] form]
    (when-not (and (symbol? sym) (map? plugin))
      (bad-declaration form (str "defplugin declaration must be a symbol and a"
                                 " map literal: " (pr-str form))))
    (when-not (keyword? (:name plugin))
      (bad-declaration form (str "defplugin `" sym "` declares no keyword :name")))
    (when-not (contains? plugin :apply)
      (bad-declaration form (str "defplugin `" sym "` declares no :apply")))
    (let [inject (try
                   (srce/normalize-inject (:inject plugin))
                   (catch Exception e
                     (throw (ex-info (str "defplugin `" sym "` has an invalid :inject: "
                                          (ex-message e))
                                     {:type :kmet.plugins/bad-declaration :form form} e))))]
      {:var (symbol (str ns-sym) (str sym))
       :name (:name plugin)
       :inject (into (sorted-map) inject)
       :provide (vec (sort-by str (:provide plugin)))
       :config? (contains? plugin :config)})))

(defn- scan-forms
  [forms ns-sym]
  (into []
        (keep #(when (defplugin-form? %) (declaration ns-sym %)))
        forms))

(defn scan-source
  "The plugin declarations in TEXT, whose namespace is NS-SYM."
  [text ns-sym]
  (scan-forms (e/parse-string-all text read-opts) ns-sym))

(defn scan-file
  "The plugin declarations in PATH."
  [path]
  (let [forms (e/parse-string-all (slurp (str path)) read-opts)
        ns-form (first forms)]
    (if (and (seq? ns-form) (= 'ns (first ns-form)) (symbol? (second ns-form)))
      (scan-forms forms (second ns-form))
      (throw (ex-info (str "source file has no ns form: " path)
                      {:type :kmet.plugins/no-ns :path (str path)})))))

(defn module-sources
  "Every module source file the scan walks."
  []
  (->> (modules/module-src-paths)
       (mapcat #(fs/glob % "**/*.{clj,cljc}"))
       (map str)
       sort))

(defn catalog
  "The catalog a fresh scan produces: `{:version 1 :plugins [entry …]}`."
  []
  {:version 1
   :plugins (->> (module-sources)
                 (mapcat scan-file)
                 (sort-by (comp str :var))
                 vec)})

(defn- render-entry [{:keys [var name inject provide config?]}]
  (str "  {:var " var
       " :name " (pr-str name)
       " :inject " (pr-str inject)
       " :provide " (pr-str provide)
       " :config? " (pr-str config?) "}"))

(defn render
  "The catalog file's exact text for CATALOG."
  [catalog-data]
  (let [plugins (:plugins catalog-data)]
    (str header
         "{:version " (:version catalog-data)
         "\n :plugins ["
         (when (seq plugins)
           (str "\n" (str/join "\n" (map render-entry plugins)) "\n "))
         "]}\n")))

(defn -main
  "Regenerate the committed catalog."
  [& _]
  (let [cat (catalog)]
    (spit catalog-path (render cat))
    (println (str "Wrote " catalog-path " (" (count (:plugins cat)) " plugins)."))))
